// Owner: manager. Shared vitest setup.
import '@testing-library/jest-dom/vitest';

// jsdom has no matchMedia. Default: no media query matches. Tests override per case.
if (typeof window !== 'undefined' && !window.matchMedia) {
  window.matchMedia = ((query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addEventListener: () => {},
    removeEventListener: () => {},
    addListener: () => {},
    removeListener: () => {},
    dispatchEvent: () => false,
  })) as typeof window.matchMedia;
}
