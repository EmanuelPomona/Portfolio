// Owner: agent/backend. Pure helpers for the media pipeline (docs/API.md §3). No I/O here.

/** Rendition steps in pixels. An image never gets a rendition wider than itself. */
export const WIDTH_STEPS = Object.freeze([640, 1024, 1600, 2400]);

/** Lowercase kebab-case segments separated by "/", then a supported image extension. */
const SOURCE_NAME = /^[a-z0-9]+(-[a-z0-9]+)*(\/[a-z0-9]+(-[a-z0-9]+)*)*\.(png|jpe?g|webp)$/;

/**
 * Manifest id for a source path relative to media-src: the path without its extension.
 * @param {string} rel e.g. "projects/sageplan.png"
 * @returns {string} e.g. "projects/sageplan"
 */
export function mediaIdFromPath(rel) {
  if (!SOURCE_NAME.test(rel)) throw new Error(`media-src/${rel}: name must be lowercase kebab-case`);
  return rel.slice(0, rel.lastIndexOf('.'));
}

/**
 * Rendition widths for an image `originalWidth` pixels wide, ascending: every step that fits,
 * plus the original width when it falls between steps (below the largest step).
 * @param {number} originalWidth
 * @returns {number[]}
 */
export function planWidths(originalWidth) {
  if (!Number.isInteger(originalWidth) || originalWidth < 1) {
    throw new RangeError(`image width must be a positive integer, got ${originalWidth}`);
  }
  const widths = WIDTH_STEPS.filter((w) => w <= originalWidth);
  const largestStep = WIDTH_STEPS[WIDTH_STEPS.length - 1];
  if (!WIDTH_STEPS.includes(originalWidth) && originalWidth < largestStep) widths.push(originalWidth);
  return widths;
}

/**
 * Public URL path of one rendition.
 * @param {string} id
 * @param {number} width
 * @param {'avif' | 'webp' | 'jpg'} ext
 * @returns {string}
 */
export function renditionPath(id, width, ext) {
  return `/media/${id}-${width}.${ext}`;
}

/** A file name this pipeline could have produced, relative to the output folder. Only these are ever deleted. */
const RENDITION_NAME = /^([a-z0-9]+(-[a-z0-9]+)*\/)*[a-z0-9]+(-[a-z0-9]+)*-\d+\.(avif|webp|jpg)$/;

/**
 * @param {string} rel forward-slash path relative to the output folder
 * @returns {boolean}
 */
export function isRenditionFile(rel) {
  return RENDITION_NAME.test(rel);
}

/**
 * Mean color of interleaved 8-bit pixels as "#rrggbb" (first three channels, rounded half up).
 * @param {Uint8Array} data
 * @param {number} channels samples per pixel, at least 3
 * @returns {string}
 */
export function meanColor(data, channels) {
  const sums = [0, 0, 0];
  const pixels = data.length / channels;
  for (let i = 0; i < data.length; i += channels) {
    sums[0] += data[i];
    sums[1] += data[i + 1];
    sums[2] += data[i + 2];
  }
  return `#${sums.map((s) => Math.round(s / pixels).toString(16).padStart(2, '0')).join('')}`;
}

/**
 * One manifest entry, in the MediaAsset shape of src/content/media.ts.
 * @param {string} id
 * @param {number[]} widths ascending rendition widths
 * @param {{ width: number, height: number }} size pixel size of the largest rendition
 * @param {string} placeholder "#rrggbb"
 */
export function manifestEntry(id, widths, size, placeholder) {
  const srcset = (/** @type {'avif' | 'webp' | 'jpg'} */ ext) =>
    widths.map((w) => `${renditionPath(id, w, ext)} ${w}w`).join(', ');
  return {
    id,
    width: size.width,
    height: size.height,
    placeholder,
    sources: [
      { type: 'image/avif', srcset: srcset('avif') },
      { type: 'image/webp', srcset: srcset('webp') },
    ],
    fallback: { src: renditionPath(id, widths[widths.length - 1], 'jpg'), srcset: srcset('jpg') },
  };
}

/**
 * The text of src/content/media.generated.ts. `manifest` must already be in key order.
 * @param {Record<string, ReturnType<typeof manifestEntry>>} manifest
 * @returns {string}
 */
export function renderManifest(manifest) {
  return [
    '// GENERATED by `npm run media` (frontend/scripts/media.mjs). Do not edit by hand.',
    '// Sources: frontend/media-src/. Shape: ./media.ts. Contract: docs/API.md §3.',
    "import type { MediaAsset } from './media';",
    '',
    `export const mediaManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, MediaAsset>;`,
    '',
  ].join('\n');
}
